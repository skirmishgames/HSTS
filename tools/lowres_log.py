#!/usr/bin/env python3
"""Low-resolution image log for unit images, recruitment tiles and option cards.

Run after every box import (needs Pillow):

    python3 tools/lowres_log.py            # summary
    python3 tools/lowres_log.py --write    # also write docs/lowres-images.csv and .md

The CSV is the list to send to the game's creators when asking for
higher-resolution files.  Thresholds (long side, pixels) are set in LIMITS.
"""
import csv, glob, json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Below these long-side sizes an image is flagged. Chosen so a tile shown full width
# on a tablet (about 1000 px wide at 2x) still looks sharp.
LIMITS = {'tile': 2000, 'unit': 600, 'option': 400}

def load(path):
    s = open(path, encoding='utf-8').read()
    return json.loads(s[s.index('= {') + 2:].rstrip().rstrip(';'))

def main():
    rows, seen = [], set()
    def add(box, nat, kind, name, rel):
        if not rel or rel in seen:
            return
        seen.add(rel)
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p):
            rows.append([box, nat, kind, name, rel, '', '', '', 'MISSING FILE'])
            return
        w, h = Image.open(p).size
        flag = 'low' if max(w, h) < LIMITS[kind] else ''
        rows.append([box, nat, kind, name, rel, w, h, os.path.getsize(p), flag])
    for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'hon-*-*.js'))):
        parts = os.path.basename(f)[:-3].split('-')
        if len(parts) != 3 or parts[2] in ('history', 'heroes', 'rules', 'tokens', 'scenarios', 'icons'):
            continue
        d = load(f)
        if 'tiles' not in d:
            continue
        box, nat = parts[1], parts[2]
        for t in d['tiles']:
            add(box, nat, 'tile', t['name'] + (' (' + t['sub'] + ')' if t.get('sub') else ''), t.get('img'))
        for n, rel in d.get('uimg', {}).items():
            add(box, nat, 'unit', n, rel)
        for o in d.get('options', []):
            add(box, nat, 'option', o['name'], o.get('img'))
    low = [r for r in rows if r[8]]
    print('images %d, flagged %d' % (len(rows), len(low)))
    for kind in LIMITS:
        k = [r for r in rows if r[2] == kind]
        if k:
            print('  %-7s %3d images, %3d flagged, largest long side %d, smallest %d' % (
                kind, len(k), len([r for r in k if r[8]]), max(max(r[5], r[6]) for r in k), min(min(r[5], r[6]) for r in k)))
    if '--write' in sys.argv:
        os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
        with open(os.path.join(ROOT, 'docs', 'lowres-images.csv'), 'w', newline='', encoding='utf-8') as fh:
            w = csv.writer(fh)
            w.writerow(['box', 'nation', 'kind', 'name', 'file', 'width_px', 'height_px', 'bytes', 'flag'])
            w.writerows(rows)
        with open(os.path.join(ROOT, 'docs', 'lowres-images.md'), 'w', encoding='utf-8') as fh:
            fh.write('# Low-resolution images\n\nGenerated by `tools/lowres_log.py --write`. %d images logged, %d flagged low (long side under %s px for tiles, units, option cards).\n\n' % (
                len(rows), len(low), '/'.join(str(LIMITS[k]) for k in ('tile', 'unit', 'option'))))
            fh.write('Purpose: list to send to the game creators when asking for higher-resolution files. Sheet scans are in the same state.\n\n')
            fh.write('| Box | Nation | Kind | Name | Size (px) | Flag |\n|---|---|---|---|---|---|\n')
            for r in rows:
                fh.write('| %s | %s | %s | %s | %sx%s | %s |\n' % (r[0], r[1], r[2], r[3], r[5], r[6], r[8]))
    return 0

if __name__ == '__main__':
    sys.exit(main())
